CREATE FUNCTION public.report_products_below_minimum(_company_id bigint) RETURNS TABLE(id bigint, description text, stock numeric, min_stock numeric, barcode text, internal_code text, sale_price numeric, purchase_price numeric, company_id bigint)
    LANGUAGE sql
    AS $$
SELECT
    p.id, p.description, p.stock, p.min_stock,
    p.barcode, p.internal_code, p.sale_price, p.purchase_price, p.company_id
FROM products p
WHERE p.company_id = _company_id AND p.stock <= p.min_stock;
$$;

CREATE FUNCTION public.valued_inventory(_company_id bigint) RETURNS TABLE(id bigint, description text, stock numeric, purchase_price numeric, total numeric)
    LANGUAGE sql
    AS $$
SELECT id, description, stock, purchase_price, (stock * purchase_price) AS total
FROM products
WHERE products.company_id = _company_id;
$$;

