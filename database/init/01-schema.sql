CREATE FUNCTION public.insert_category(_description text, _company_id bigint, _color text) RETURNS void
    LANGUAGE plpgsql
    AS $$
begin
  perform 1 from categories where description = _description and company_id = _company_id;
  if found then
    raise exception 'Datos duplicados';
  else
    insert into categories(description, company_id, color)
    values (_description, _company_id, _color);
  end if;
end;
$$;

CREATE FUNCTION public.insert_brand(_description text, _company_id bigint) RETURNS void
    LANGUAGE plpgsql
    AS $$
begin
  perform 1 from brands where description = _description and company_id = _company_id;
  if found then
    raise exception 'Datos duplicados';
  else
    insert into brands(description, company_id)
    values (_description, _company_id);
  end if;
end;
$$;

CREATE FUNCTION public.edit_brand(_description text, _company_id bigint, _id bigint) RETURNS void
    LANGUAGE plpgsql
    AS $$
begin
  perform 1 from brands where description = _description and company_id = _company_id and id != _id;
  if found then
    raise exception 'Datos duplicados';
  else
    update brands set description = _description
    where id = _id;
  end if;
end;
$$;

CREATE FUNCTION public.insert_product(_description text, _brand_id bigint, _stock numeric, _min_stock numeric, _barcode text, _internal_code text, _sale_price numeric, _purchase_price numeric, _category_id bigint, _company_id bigint) RETURNS void
    LANGUAGE plpgsql
    AS $$
begin
  perform 1 from products where description = _description and company_id = _company_id;
  if found then
    raise exception 'Datos duplicados';
  else
    insert into products(description, brand_id, stock, min_stock, barcode, internal_code, sale_price, purchase_price, category_id, company_id)
    values (_description, _brand_id, _stock, _min_stock, _barcode, _internal_code, _sale_price, _purchase_price, _category_id, _company_id);
  end if;
end;
$$;
