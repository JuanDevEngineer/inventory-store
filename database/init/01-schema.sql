CREATE FUNCTION public.get_company_kardex(_company_id bigint) RETURNS TABLE(id bigint, description text, date text, quantity double precision, type text, detail text, name text, stock numeric, status bigint, product_id bigint)
    LANGUAGE sql
    AS $$
