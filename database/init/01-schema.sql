-- ---------------------------------------------------------------------
-- Tables
-- ---------------------------------------------------------------------

CREATE TABLE public.users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text DEFAULT 'generico'::text NOT NULL,
    document_number text DEFAULT '-'::text,
    phone text DEFAULT '-'::text,
    address text DEFAULT '-'::text,
    registered_at date NOT NULL,
    status text DEFAULT 'activo'::text,
    user_type text NOT NULL,
    auth_id text NOT NULL,
    document_type text DEFAULT '-'::text,
    email text DEFAULT '-'::text
);

CREATE TABLE public.companies (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    currency_symbol text,
    admin_user_id bigint REFERENCES public.users(id) ON DELETE CASCADE
);

CREATE TABLE public.company_users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    company_id bigint NOT NULL REFERENCES public.companies(id),
    user_id bigint REFERENCES public.users(id) ON DELETE CASCADE
);

CREATE TABLE public.categories (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    description text NOT NULL,
    color text,
    company_id bigint REFERENCES public.companies(id) ON DELETE CASCADE
);

CREATE TABLE public.brands (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    description text NOT NULL,
    company_id bigint REFERENCES public.companies(id) ON DELETE CASCADE
);

CREATE TABLE public.modules (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name text NOT NULL,
    "check" boolean DEFAULT false
);

CREATE TABLE public.permissions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    module_id bigint REFERENCES public.modules(id)
);

CREATE TABLE public.products (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    description text NOT NULL,
    brand_id bigint REFERENCES public.brands(id),
    stock numeric,
    min_stock numeric,
    barcode text,
    internal_code text,
    sale_price numeric,
    purchase_price numeric,
    category_id bigint REFERENCES public.categories(id),
    company_id bigint REFERENCES public.companies(id) ON DELETE CASCADE
);

-- Stock movements (entries and exits) per product
CREATE TABLE public.kardex (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date date NOT NULL,
    type text,
    user_id bigint REFERENCES public.users(id),
    product_id bigint REFERENCES public.products(id),
    quantity double precision,
    company_id bigint REFERENCES public.companies(id),
    detail text,
    status bigint DEFAULT '1'::bigint
);

