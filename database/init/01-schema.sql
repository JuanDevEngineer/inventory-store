CREATE FUNCTION public.get_user_companies(_user_id bigint) RETURNS SETOF public.companies
    LANGUAGE sql
    AS $$
SELECT companies.*
FROM companies
    INNER JOIN company_users ON company_users.company_id = companies.id
    INNER JOIN users ON company_users.user_id = users.id
WHERE company_users.user_id = _user_id;
$$;

CREATE FUNCTION public.count_users_by_company(_company_id bigint) RETURNS integer
    LANGUAGE sql
    AS $$
SELECT count(*)::integer FROM company_users WHERE company_id = _company_id;
$$;

CREATE FUNCTION public.get_company_staff(_company_id bigint) RETURNS TABLE(id bigint, name text, user_type text, status text, email text, document_number text, phone text, address text, document_type text)
    LANGUAGE sql
    AS $$
SELECT u.id, u.name, u.user_type, u.status, u.email, u.document_number, u.phone, u.address, u.document_type
FROM company_users
    INNER JOIN users u ON u.id = company_users.user_id
WHERE company_users.company_id = _company_id;
$$;

CREATE FUNCTION public.search_company_staff(_company_id bigint, _search text) RETURNS TABLE(id bigint, name text, user_type text, status text, email text, document_number text, phone text, address text, document_type text)
    LANGUAGE sql
    AS $$
SELECT u.id, u.name, u.user_type, u.status, u.email, u.document_number, u.phone, u.address, u.document_type
FROM company_users
    INNER JOIN users u ON u.id = company_users.user_id
WHERE u.name ILIKE '%' || _search || '%' AND company_users.company_id = _company_id;
$$;

CREATE FUNCTION public.get_company_products(_company_id bigint) RETURNS TABLE(id bigint, description text, brand_id bigint, stock numeric, min_stock numeric, barcode text, internal_code text, sale_price numeric, purchase_price numeric, category_id bigint, company_id bigint, brand text, category text, color text)
    LANGUAGE sql
    AS $$
SELECT
    p.id, p.description, p.brand_id, p.stock, p.min_stock,
    p.barcode, p.internal_code, p.sale_price, p.purchase_price,
    p.category_id, p.company_id,
    b.description AS brand,
    c.description AS category,
    c.color
FROM products p
    INNER JOIN categories c ON c.id = p.category_id
    INNER JOIN brands b ON b.id = p.brand_id
WHERE p.company_id = _company_id;
$$;

