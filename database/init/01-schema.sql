-- A new superadmin gets a default company and access to every module
CREATE FUNCTION public.insert_default_permissions() RETURNS trigger
    LANGUAGE plpgsql
    AS $$
declare item record;
begin
  if new.user_type = 'superadmin' then
    insert into companies(name, currency_symbol, admin_user_id)
    values ('Generica', 'S/.', new.id);
  end if;
  for item in
    select id from modules
  loop
    if new.user_type = 'superadmin' then
      insert into permissions(user_id, module_id)
      values (new.id, item.id);
    end if;
  end loop;
  return new;
end
$$;

-- A new company gets a default brand, category and its admin assigned
CREATE FUNCTION public.insert_company_defaults() RETURNS trigger
    LANGUAGE plpgsql
    AS $$
begin
  insert into brands(description, company_id)
  values ('Generica', new.id);
  insert into categories(description, color, company_id)
  values ('General', '#FF5722', new.id);
  insert into company_users(company_id, user_id)
  values (new.id, new.admin_user_id);
  return new;
end
$$;

CREATE FUNCTION public.update_stock() RETURNS trigger
    LANGUAGE plpgsql
    AS $$
declare product_stock numeric;
begin
  if new.type = 'entrada' then
    update products
    set stock = stock + new.quantity
    where id = new.product_id;
  else
    select into product_stock stock
    from products
    where id = new.product_id;
    if product_stock > new.quantity then
      update products
      set stock = stock - new.quantity
      where id = new.product_id;
    else
      raise exception 'Stock agotado para este producto';
    end if;
  end if;
  return new;
end;
$$;

CREATE FUNCTION public.cancel_kardex_entry() RETURNS trigger
    LANGUAGE plpgsql
    AS $$
begin
  insert into kardex(date, type, user_id, product_id, quantity, company_id, detail, status)
  values (now(), old.type || '-anulado', old.user_id, old.product_id, old.quantity, old.company_id, old.detail || '-anulado', 0);

  update products
  set stock = stock + old.quantity
  where id = new.product_id;
  return old;
end;
$$;

CREATE TRIGGER insert_default_permissions_trigger AFTER INSERT ON public.users FOR EACH ROW EXECUTE FUNCTION public.insert_default_permissions();
CREATE TRIGGER insert_company_defaults_trigger AFTER INSERT ON public.companies FOR EACH ROW EXECUTE FUNCTION public.insert_company_defaults();
CREATE TRIGGER update_stock_trigger AFTER INSERT ON public.kardex FOR EACH ROW EXECUTE FUNCTION public.update_stock();
CREATE TRIGGER cancel_kardex_entry_trigger BEFORE DELETE ON public.kardex FOR EACH ROW EXECUTE FUNCTION public.cancel_kardex_entry();

